"""Exploratory data analysis: writes reports/eda.md and figures.

EDA here answers: what does the data look like, is it clean, is it balanced, and is
there anything (duplicates, noisy labels, brand names) that could mislead the model?
"""
from __future__ import annotations

import re
from collections import Counter

import emoji
import matplotlib.pyplot as plt
import pandas as pd
from sklearn.feature_extraction.text import ENGLISH_STOP_WORDS

from . import config
from .data import AIRLINE, AIRLINE_TEXT_ARTIFACTS
from .reporting import SENTIMENT_COLORS, md_table, pct, save_figure, write_markdown

# For DISPLAY ONLY (most-common-words tables). The model itself keeps stop words,
# and negations are kept even here because they matter for sentiment.
_DISPLAY_STOP_WORDS = (set(ENGLISH_STOP_WORDS) - {"not", "no", "never", "nothing", "cannot"}) | {"<user>", "<url>", "amp"}


def _text_quality(texts: pd.Series) -> list[list]:
    checks = {
        "Contains a URL": r"https?://|www\.",
        "Contains an @mention": r"@\w+",
        "Contains a #hashtag": r"#\w+",
        "Contains a text emoticon like :) or :(": r"[:;=]-?[)(DPp/]",
        "Contains an ALL-CAPS word (3+ letters)": r"\b[A-Z]{3,}\b",
        "Contains an elongated word (e.g. sooo)": r"([A-Za-z])\1{2,}",
        "Contains HTML entities (&amp; etc.)": r"&\w+;",
    }
    # Python's `re` (not pandas' Arrow engine) because the elongation check needs a backreference.
    rows = [[name, pct(texts.map(lambda t, p=re.compile(pattern): bool(p.search(t))).mean())]
            for name, pattern in checks.items()]
    rows.append(["Contains an emoji", pct(texts.map(lambda t: emoji.emoji_count(t) > 0).mean())])
    return rows


def _top_tokens(df: pd.DataFrame, label: str, k: int = 15) -> str:
    counts: Counter[str] = Counter()
    for text in df.loc[df["label"] == label, "clean_text"]:
        counts.update(t for t in text.split() if t not in _DISPLAY_STOP_WORDS and len(t) > 1)
    return ", ".join(f"{token} ({n})" for token, n in counts.most_common(k))


def run(raw: pd.DataFrame, df: pd.DataFrame, train: pd.DataFrame, test: pd.DataFrame, cleaning_report: dict) -> None:
    lines = [
        "# Exploratory Data Analysis",
        "",
        "Generated by `python -m sentiment_ml.pipeline`. Dataset: "
        f"[{AIRLINE.name}]({AIRLINE.homepage}) (licence: {AIRLINE.licence}).",
        "",
        "## 1. Schema",
        "",
    ]
    schema_rows = [[col, str(raw[col].dtype), f"{raw[col].isna().sum():,}", pct(raw[col].isna().mean())]
                   for col in raw.columns]
    lines += md_table(["Column", "Type", "Missing", "Missing %"], schema_rows)
    lines += [
        "",
        "Only `text` (input) and `airline_sentiment` (label) are used for training. "
        "`airline_sentiment_confidence` is used for error analysis (label noise). Columns such as "
        "`tweet_coord`, `negativereason_gold` and `airline_sentiment_gold` are mostly empty and unused.",
        "",
        "## 2. Data quality and cleaning",
        "",
    ]
    lines += md_table(["Step", "Rows"], [[k.replace("_", " "), f"{v:,}"] for k, v in cleaning_report.items()])
    lines += [
        "",
        "- **Find-and-replace artifacts (repaired):** the published CSV replaced every `late` and `cancel` "
        "(and some `book`) substrings with complaint-category names, even inside other words. The natural "
        "words *late* and *cancel* appear zero times, so a model trained on the raw text would never learn "
        "them. We reverse the substitution before cleaning:",
        "",
    ]
    raw_text = raw["text"].astype(str)
    artifact_rows = []
    for artifact, original in AIRLINE_TEXT_ARTIFACTS:
        hits = raw_text[raw_text.str.contains(artifact, regex=False)]
        example = hits.str.findall(rf"\w*{re.escape(artifact)}\w*").explode().value_counts().index[:3]
        artifact_rows.append([f"`{artifact}` → `{original}`", f"{len(hits):,}",
                              ", ".join(f"`{w}` → `{w.replace(artifact, original)}`" for w in example)])
    lines += md_table(["Repair", "Tweets affected", "Examples"], artifact_rows)
    lines += [
        "",
        "- **Duplicate tweet IDs** were scraped twice; one copy is kept.",
        "- **Conflicting-label duplicates**: the same cleaned text labelled differently by annotators. "
        "Every copy is dropped because neither label can be trusted.",
        "- **Cleaned-text duplicates** (e.g. the same message sent to two airlines) are dropped *before* "
        "the split so an identical input cannot appear in both train and test (leakage).",
        "",
        "### Text quality (raw tweets)",
        "",
    ]
    lines += md_table(["Feature", "Share of tweets"], _text_quality(raw["text"].astype(str)))

    # Label distribution
    counts = df["label"].value_counts().reindex(config.LABELS)
    fig, ax = plt.subplots(figsize=(5, 3))
    ax.bar(counts.index, counts.values, color=[SENTIMENT_COLORS[label] for label in counts.index])
    ax.set_title("Label distribution (after cleaning)")
    ax.set_ylabel("Tweets")
    for i, v in enumerate(counts.values):
        ax.text(i, v, f"{v:,}\n({v / counts.sum():.0%})", ha="center", va="bottom", fontsize=8)
    ax.margins(y=0.2)
    label_fig = save_figure(fig, "label_distribution.png")
    lines += [
        "",
        "## 3. Label distribution",
        "",
        f"![Label distribution]({label_fig})",
        "",
    ]
    lines += md_table(["Label", "Tweets", "Share"], [[lbl, f"{n:,}", pct(n / counts.sum())] for lbl, n in counts.items()])
    lines += [
        "",
        "The classes are **imbalanced** (negative is the majority). A model that always answers "
        "*negative* would already reach about this share in accuracy while being useless, which is why "
        "macro-F1 is the headline metric and class weights are evaluated during training.",
        "",
        "The original labels are already Negative / Neutral / Positive, so no label mapping was needed "
        "(they are only lower-cased).",
    ]

    # Text length
    lengths = df.assign(chars=df["text"].str.len(), tokens=df["clean_text"].str.split().str.len())
    fig, ax = plt.subplots(figsize=(6, 3))
    for label in config.LABELS:
        ax.hist(lengths.loc[lengths["label"] == label, "tokens"], bins=30, alpha=0.55, label=label,
                color=SENTIMENT_COLORS[label])
    ax.set_title("Tokens per tweet by label")
    ax.set_xlabel("Tokens after cleaning")
    ax.set_ylabel("Tweets")
    ax.legend()
    length_fig = save_figure(fig, "text_length.png")
    stats = lengths.groupby("label")[["chars", "tokens"]].median().reindex(config.LABELS)
    lines += [
        "",
        "## 4. Text length",
        "",
        f"![Text length]({length_fig})",
        "",
    ]
    lines += md_table(["Label", "Median characters", "Median tokens"],
                      [[lbl, f"{row.chars:.0f}", f"{row.tokens:.0f}"] for lbl, row in stats.iterrows()])
    lines += ["", "Negative tweets are longer: complaints come with explanations; praise tends to be short."]

    # Common tokens
    lines += ["", "## 5. Most common words per label", "",
              "(Stop words hidden in this table for readability only. The model keeps them, including negations.)", ""]
    lines += md_table(["Label", "Top tokens (count)"], [[lbl, _top_tokens(df, lbl)] for lbl in config.LABELS])

    # Brand x sentiment
    crosstab = pd.crosstab(df["airline"], df["label"], normalize="index").reindex(columns=list(config.LABELS))
    lines += [
        "",
        "## 6. Sentiment by airline",
        "",
        "Each airline has a very different mix. A model that saw the airline handle could learn "
        "\"@united means negative\", a shortcut that would not transfer to other brands. "
        "That is why @mentions are replaced by `<user>` during cleaning.",
        "",
    ]
    lines += md_table(["Airline", "Tweets"] + list(config.LABELS),
                      [[airline, f"{(df['airline'] == airline).sum():,}"] + [pct(row[lbl]) for lbl in config.LABELS]
                       for airline, row in crosstab.iterrows()])

    # Label confidence
    conf = df["label_confidence"]
    fig, ax = plt.subplots(figsize=(5, 3))
    ax.hist(conf, bins=20, color="#6366f1")
    ax.set_title("Annotator agreement (label confidence)")
    ax.set_xlabel("airline_sentiment_confidence")
    ax.set_ylabel("Tweets")
    conf_fig = save_figure(fig, "label_confidence.png")
    lines += [
        "",
        "## 7. Label quality",
        "",
        f"![Label confidence]({conf_fig})",
        "",
        f"- {pct((conf == 1).mean())} of tweets have full annotator agreement (confidence = 1.0).",
        f"- {pct((conf < 0.7).mean())} have confidence below 0.7. These labels are noisy, which caps the "
        "accuracy any model can reach and is analysed in the evaluation report.",
    ]

    reasons = df.loc[df["label"] == "negative", "negativereason"].value_counts().head(8)
    lines += ["", "### Why customers were negative (annotated reasons, not used for training)", ""]
    lines += md_table(["Reason", "Tweets"], [[r, f"{n:,}"] for r, n in reasons.items()])

    created = pd.to_datetime(raw["tweet_created"], errors="coerce", utc=True)
    lines += [
        "",
        "## 8. Timestamps",
        "",
        f"Tweets were posted between **{created.min():%Y-%m-%d}** and **{created.max():%Y-%m-%d}** (about one week). "
        "These dates are *not* used by the dashboard: its date filters use the time each prediction was made, "
        "as required by the brief. We never fabricate timestamps.",
        "",
        "## 9. Train / test split",
        "",
        f"Stratified {1 - config.TEST_SIZE:.0%} / {config.TEST_SIZE:.0%} split with `random_state={config.RANDOM_STATE}`, "
        "done after cleaning and de-duplication and **before** any vectoriser is fitted.",
        "",
    ]
    split_rows = []
    for name, part in (("train", train), ("test", test)):
        dist = part["label"].value_counts(normalize=True)
        split_rows.append([name, f"{len(part):,}"] + [pct(dist.get(lbl, 0)) for lbl in config.LABELS])
    lines += md_table(["Split", "Rows"] + list(config.LABELS), split_rows)

    lines += ["", "## 10. Cleaning examples", ""]
    examples = df.sample(6, random_state=config.RANDOM_STATE)
    lines += md_table(["Raw tweet", "Cleaned (what the model sees)"],
                      [[_escape(r.text), _escape(r.clean_text)] for r in examples.itertuples()])

    write_markdown(config.REPORTS_DIR / "eda.md", lines)


def _escape(text: str) -> str:
    return re.sub(r"([|<>])", r"\\\1", text.replace("\n", " "))
