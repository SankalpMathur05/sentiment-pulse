"""Compare the two candidate datasets side by side before choosing one.

Run:  python scripts/dataset_bakeoff.py
Writes: reports/dataset_bakeoff.md

For each dataset we report size, label balance, data-quality counts, text length and a
quick 5-fold cross-validated macro-F1 with the same baseline model. We also train on
one dataset and test on the other to see how well each transfers (domain shift).
"""
from __future__ import annotations

from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import f1_score
from sklearn.model_selection import StratifiedKFold, cross_val_score
from sklearn.pipeline import make_pipeline

from sentiment_ml import config
from sentiment_ml.artifacts import sha256_file
from sentiment_ml.data import AIRLINE, TWEETEVAL_SPLITS, load_tweeteval, prepare, prepare_airline
from sentiment_ml.preprocessing import tokenize


def baseline():
    return make_pipeline(
        TfidfVectorizer(tokenizer=tokenize, token_pattern=None, lowercase=False, ngram_range=(1, 2), min_df=2,
                        sublinear_tf=True),
        LogisticRegression(C=1.0, class_weight="balanced", max_iter=2000, random_state=config.RANDOM_STATE),
    )


def summarise(name, df, report, extra):
    cv = StratifiedKFold(n_splits=config.CV_FOLDS, shuffle=True, random_state=config.RANDOM_STATE)
    scores = cross_val_score(baseline(), df["clean_text"], df["label"], cv=cv, scoring="f1_macro", n_jobs=-1)
    dist = df["label"].value_counts(normalize=True)
    lengths = df["text"].str.len()
    return {
        "Dataset": name,
        "Rows (raw → after cleaning)": f"{report['rows_raw']:,} → {report['rows_final']:,}",
        "Negative / Neutral / Positive": " / ".join(f"{dist.get(lbl, 0):.0%}" for lbl in config.LABELS),
        "Duplicates removed": f"{report['duplicate_clean_text_dropped'] + report['conflicting_label_duplicates_dropped']:,}",
        "Median length (chars)": f"{lengths.median():.0f}",
        "5-fold CV macro-F1 (baseline)": f"{scores.mean():.3f} ± {scores.std():.3f}",
        **extra,
    }


def main() -> None:
    airline, airline_report = prepare_airline()
    tweeteval_raw = load_tweeteval()
    tweeteval, tweeteval_report = prepare(tweeteval_raw, text_col="text", label_col="label")

    rows = [
        summarise("Twitter US Airline Sentiment", airline, airline_report, {
            "Topic": "Customers talking to 6 US airline brands (Feb 2015)",
            "Licence": AIRLINE.licence,
            "Label-quality info": "Yes: per-tweet annotator confidence",
            "Timestamps / brand": "Yes / Yes",
        }),
        summarise("TweetEval sentiment", tweeteval, tweeteval_report, {
            "Topic": "General tweets on many topics (SemEval-2017)",
            "Licence": TWEETEVAL_SPLITS["train"].licence,
            "Label-quality info": "No",
            "Timestamps / brand": "No / No",
        }),
    ]

    # Domain shift: fit on all of one dataset, score on all of the other.
    fit_airline = baseline().fit(airline["clean_text"], airline["label"])
    fit_tweeteval = baseline().fit(tweeteval["clean_text"], tweeteval["label"])
    airline_to_te = f1_score(tweeteval["label"], fit_airline.predict(tweeteval["clean_text"]), average="macro")
    te_to_airline = f1_score(airline["label"], fit_tweeteval.predict(airline["clean_text"]), average="macro")

    keys = list(rows[0].keys())
    lines = [
        "# Dataset bake-off",
        "",
        "Generated by `scripts/dataset_bakeoff.py`. Same cleaning and same baseline model "
        "(TF-IDF 1–2-grams + Logistic Regression, balanced class weights) for both datasets.",
        "",
        "| | " + " | ".join(r["Dataset"] for r in rows) + " |",
        "|---|" + "---|" * len(rows),
    ]
    lines += [f"| {k} | " + " | ".join(str(r[k]) for r in rows) + " |" for k in keys if k != "Dataset"]
    lines += [
        "",
        "## Domain shift (train on one, test on the other)",
        "",
        "| Trained on → tested on | Macro-F1 |",
        "|---|---|",
        f"| Airline → TweetEval | {airline_to_te:.3f} |",
        f"| TweetEval → Airline | {te_to_airline:.3f} |",
        "",
        "## Cleaning reports",
        "",
        "| Step | Airline | TweetEval |",
        "|---|---|---|",
    ]
    lines += [f"| {k} | {airline_report.get(k, '–')} | {tweeteval_report.get(k, '–')} |" for k in airline_report]
    out = config.REPORTS_DIR / "dataset_bakeoff.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines))
    print(f"\nAirline CSV sha256: {sha256_file(AIRLINE.path)}")


if __name__ == "__main__":
    main()
